package com.mini.me_core.feature.agent.domain.execution.tool.git

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Git 纪律内核回归：提交规范、tag 命名、远端 URL 治理、shell 转义。
 * 规则与 .githooks/commit-msg / AGENTS.md 发版规范同源。
 */
class GitDisciplineTest {

    @Test
    fun commitSubject_validForms() {
        assertNull(GitDiscipline.commitSubjectViolation("feat(agent): 新增流式工具调用"))
        assertNull(GitDiscipline.commitSubjectViolation("fix: 修复空气泡"))
        assertNull(GitDiscipline.commitSubjectViolation("refactor(git)!: 重构纪律内核"))
        assertNull(GitDiscipline.commitSubjectViolation("chore(deps): 升级依赖"))
        assertNull(GitDiscipline.commitSubjectViolation("perf: 优化启动"))
    }

    @Test
    fun commitSubject_autoGeneratedSkipped() {
        assertNull(GitDiscipline.commitSubjectViolation("Merge branch 'main' into feature"))
        assertNull(GitDiscipline.commitSubjectViolation("Revert \"feat: x\""))
        assertNull(GitDiscipline.commitSubjectViolation("fixup! feat(agent): x"))
        assertNull(GitDiscipline.commitSubjectViolation("squash! fix: y"))
    }

    @Test
    fun commitSubject_violations() {
        assertEquals("提交信息为空", GitDiscipline.commitSubjectViolation("   "))
        assertTrue(GitDiscipline.commitSubjectViolation("随便写点什么")!!.contains("type"))
        assertTrue(GitDiscipline.commitSubjectViolation("feat:")!!.contains("':'"))
        assertTrue(GitDiscipline.commitSubjectViolation("feat:x")!!.contains("<type>(<scope>): <subject>"))
    }

    @Test
    fun tagName_rules() {
        assertTrue(GitDiscipline.TAG_REGEX.matches("v1.2.3"))
        assertTrue(GitDiscipline.TAG_REGEX.matches("v0.0.1.4")) // 本项目实际四段版本
        assertTrue(GitDiscipline.TAG_REGEX.matches("v0.0.1.4-rc1"))
        assertTrue(GitDiscipline.TAG_REGEX.matches("v2.0.0-beta2"))
        assertFalse(GitDiscipline.TAG_REGEX.matches("1.2.3"))
        assertFalse(GitDiscipline.TAG_REGEX.matches("v1.2"))
        assertFalse(GitDiscipline.TAG_REGEX.matches("release-1.2.3"))
        assertFalse(GitDiscipline.TAG_REGEX.matches("v1.2.3-rc")) // 缺序号
        assertFalse(GitDiscipline.TAG_REGEX.matches("v1.2.3.4.5")) // 五段不支持
        assertFalse(GitDiscipline.TAG_REGEX.matches("v1.2.3.4-rc")) // 四段+后缀同样要求序号
    }

    @Test
    fun remoteUrl_allowedForms() {
        assertNull(GitDiscipline.remoteUrlRejectionReason("https://github.com/org/repo.git"))
        assertNull(GitDiscipline.remoteUrlRejectionReason("http://gitlab.internal/team/repo.git"))
        assertNull(GitDiscipline.remoteUrlRejectionReason("ssh://git@host:2222/org/repo.git"))
        assertNull(GitDiscipline.remoteUrlRejectionReason("git@github.com:org/repo.git"))
        assertNull(GitDiscipline.remoteUrlRejectionReason("https://user@github.com/org/repo.git")) // 无密码的 user@ 允许
    }

    @Test
    fun remoteUrl_rejections() {
        assertTrue(GitDiscipline.remoteUrlRejectionReason("")!!.contains("为空"))
        assertTrue(GitDiscipline.remoteUrlRejectionReason("ftp://host/repo.git")!!.contains("仅支持"))
        assertTrue(GitDiscipline.remoteUrlRejectionReason("https://user:pass@github.com/org/repo.git")!!.contains("不得内联账号密码"))
        assertTrue(GitDiscipline.remoteUrlRejectionReason("file:///srv/repo.git")!!.contains("file://"))
    }

    @Test
    fun remoteAndDirNames() {
        assertTrue(GitDiscipline.isValidRemoteName("origin"))
        assertTrue(GitDiscipline.isValidRemoteName("up-stream.1"))
        assertFalse(GitDiscipline.isValidRemoteName(""))
        assertFalse(GitDiscipline.isValidRemoteName("bad name"))
        assertFalse(GitDiscipline.isValidRemoteName("../escape"))
        assertFalse(GitDiscipline.isValidCloneDir("a/b"))
    }

    @Test
    fun shellQuote_injectionSafety() {
        assertEquals("plain", GitDiscipline.shellQuote("plain"))
        assertEquals("''", GitDiscipline.shellQuote(""))
        assertEquals("'a b'", GitDiscipline.shellQuote("a b"))
        // 单引号注入必须被转义，不能逃逸出引号上下文
        assertEquals("'it'\\''s'", GitDiscipline.shellQuote("it's"))
        assertEquals("'$(whoami)'", GitDiscipline.shellQuote("$(whoami)"))
        assertEquals("'; rm -rf /'", GitDiscipline.shellQuote("; rm -rf /"))
    }
}
