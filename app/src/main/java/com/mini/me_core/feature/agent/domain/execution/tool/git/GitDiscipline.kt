package com.mini.me_core.feature.agent.domain.execution.tool.git

/**
 * Git 纪律共享内核：提交规范、tag 命名、远端 URL 治理、shell 转义。
 *
 * 规则来源与 [GitOpsTool] 完全同源（.githooks/commit-msg + AGENTS.md 发版规范），
 * 收敛至此单一真相源，避免 gitops / git_remote 两个工具各持一份正则漂移。
 * 纯函数、无 IO，供工具层与单测直接消费。
 */
internal object GitDiscipline {

    /** Conventional Commits 允许的 type，对齐 .githooks/commit-msg。 */
    val TYPES = listOf(
        "feat", "fix", "refactor", "docs", "style",
        "chore", "ci", "build", "perf", "test"
    )

    /** 建议 scope（与 AGENTS.md 提交规范对齐）。 */
    val RECOMMENDED_SCOPES = listOf(
        "agent", "settings", "terminal", "workspace",
        "git", "ui", "mcp", "db", "core", "docs", "build", "deps"
    )

    /** Conventional Commits 正则：^<type>(<scope>)?[!]?: <subject>，:后至少一个非空字符。 */
    val COMMIT_REGEX = Regex("^(${TYPES.joinToString("|")})(\\([A-Za-z0-9._-]+\\))?!?: .+")

    /**
     * tag 名必须匹配 vX.Y.Z / vX.Y.Z.N 或其后缀 -rcN/-beta/-alpha/-devN 的语义化版本。
     * 四段为本项目实际版本命名（历史 tag 全为 v0.0.x.N，见 git tag / build.gradle.kts gitVersionName）。
     */
    val TAG_REGEX = Regex("""^v\d+\.\d+\.\d+(?:\.\d+)?(?:-(?:rc|beta|alpha|dev)\d+)?$""")

    /** 远端 URL 允许的协议头（ssh 形态 git@host:path 单独判定）。 */
    private val URL_PROTOCOLS = listOf("https://", "http://", "ssh://", "git://")

    /** 远端 URL 协议/形态白名单外的拒绝原因（null 表示合法）。 */
    fun remoteUrlRejectionReason(url: String): String? {
        val u = url.trim()
        // when 单出口：file:// 显式拒绝的文案优先于协议白名单的通用提示
        return when {
            u.isBlank() -> "远端 URL 为空"
            u.startsWith("git@") -> null // ssh 短写形态
            u.startsWith("file://") -> "拒绝 file:// 本地路径远端"
            URL_PROTOCOLS.none { u.startsWith(it) } ->
                "仅支持 https:// http:// ssh:// git:// 或 git@host:path 形态，拒绝：${u.take(40)}"
            // 内联凭据（user:pass@host）一律拒绝：凭据必须走 credential.helper 链，不得落进 remote 配置
            hasInlineCredentials(u) ->
                "远端 URL 不得内联账号密码（user:pass@host），请改用凭据库（credential.helper 自动注入）"
            else -> null
        }
    }

    /** URL 是否内联 user:pass@ 形式的账号密码（user@ 无密码形态放行）。 */
    private fun hasInlineCredentials(url: String): Boolean {
        val hostPart = url.substringAfter("://").substringBefore('/')
        val userInfo = hostPart.substringBefore('@', "")
        return '@' in hostPart && userInfo.contains(':')
    }

    /** 远端名治理：字母数字与 . _ - 组成，禁止路径分隔与空格。 */
    fun isValidRemoteName(name: String): Boolean =
        name.isNotBlank() && name.all { it.isLetterOrDigit() || it in "._-" }

    /** clone 目标目录名治理：与远端名同规则（防 ../../ 逃逸与空格路径）。 */
    fun isValidCloneDir(dir: String): Boolean = isValidRemoteName(dir)

    /**
     * 对单个 shell 参数做单引号转义。仅用于拼接 `git ...` 命令，
     * 与 GitRepositoryImpl.shellQuote 同一策略（含空格/特殊字符安全传递）。
     */
    fun shellQuote(arg: String): String {
        if (arg.isEmpty()) return "''"
        if (arg.all { it.isLetterOrDigit() || it in "_.@/:=+,-" }) return arg
        return "'" + arg.replace("'", "'\\''") + "'"
    }

    /**
     * 校验提交信息首行是否符合 Conventional Commits。
     * @return null 表示合规；非 null 为给模型的修正提示。
     */
    fun commitSubjectViolation(firstLine: String): String? {
        val line = firstLine.trim()
        if (line.isBlank()) return "提交信息为空"
        // 自动生成的提交（merge/revert/fixup/squash）按 hooks 同款规则跳过
        val autoGenerated = line.startsWith("Merge ") || line.startsWith("Revert ") ||
            line.startsWith("fixup!") || line.startsWith("squash!")
        if (autoGenerated) return null
        if (COMMIT_REGEX.matches(line)) return null
        val subject = line.substringAfter(":", "").trim()
        val hint = when {
            line.substringBefore(':').substringBefore('(').trim() !in TYPES ->
                "type 必须是 ${TYPES.joinToString("/")} 之一（当前：'${line.substringBefore(':').substringBefore('(').trim()}'）"
            subject.isEmpty() -> "':' 后必须至少跟一个非空字符作为 subject"
            else -> "需符合 <type>(<scope>): <subject>；可用 type 见上方枚举，scope 建议 ${RECOMMENDED_SCOPES.joinToString("/")}"
        }
        return hint
    }
}
